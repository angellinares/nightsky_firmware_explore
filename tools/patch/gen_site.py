#!/usr/bin/env python3
"""Generate site/js/nightsky-code.js, the patch data of the web patcher.

    python tools/patch/gen_site.py

Steps:
 1. Run build_patch.py (release build, no --debug).
 2. Compare the patched image with the stock image. Every changed byte must
    sit at a known hook site. The cave sits past the end of the stock image.
 3. Write the patch data: the cave blob (our code), the hook edits (our
    branch instructions), the SHA-256 of the stock file and of the expected
    output, and the release history from history.json.

The data file holds no vendor bytes. The page checks the upload by hash.
Needs the stock 1.07 files in firmware-backup/v1.07/ (not in the repo).
"""
import base64, hashlib, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import build_patch as bp

OUT_JS = os.path.join(ROOT, "site", "js", "nightsky-code.js")
HISTORY = os.path.join(HERE, "history.json")
HOOKS = [bp.HOOK_REC, bp.HOOK_POLL, bp.HOOK_LOAD, bp.HOOK_SAVE, bp.HOOK_JR]


def sha(b):
    return hashlib.sha256(b).hexdigest()


def main():
    r = subprocess.run([sys.executable, os.path.join(HERE, "build_patch.py")],
                       capture_output=True, text=True)
    if r.returncode != 0 or "build: release" not in r.stdout:
        print(r.stdout, r.stderr)
        sys.exit("release build failed")
    stock_syx = open(bp.STOCK_SYX, "rb").read()
    stock = open(bp.STOCK_BIN, "rb").read()
    img = open(bp.OUT_BIN, "rb").read()
    out_syx = open(bp.OUT_SYX, "rb").read()

    edits = []
    i = 0
    while i < len(stock):
        if stock[i] == img[i]:
            i += 1
            continue
        site = next((h for h in HOOKS if h - bp.IMG_BASE <= i < h - bp.IMG_BASE + 4), None)
        if site is None:
            sys.exit(f"changed byte at {bp.IMG_BASE + i:#x} is not a hook site")
        off = site - bp.IMG_BASE
        edits.append({"addr": site, "bytes": img[off:off + 4].hex()})
        i = off + 4
    assert len(edits) == len(HOOKS), f"expected {len(HOOKS)} hook edits, got {len(edits)}"
    assert img[len(stock):bp.CAVE_OFF] == b"\xFF" * (bp.CAVE_OFF - len(stock))
    cave = img[bp.CAVE_OFF:].rstrip(b"\xFF")

    hist = json.load(open(HISTORY))
    rel = hist["releases"][0]
    data = {
        "version": rel["version"],
        "build": rel["build"],
        "stockName": hist["stock"],
        "stockSyxSha256": sha(stock_syx),
        "stockImageSha256": sha(stock),
        "imageBase": bp.IMG_BASE,
        "caveAddr": bp.CAVE_ADDR,
        "cave": base64.b64encode(cave).decode(),
        "edits": edits,
        "crcEnd": bp.CRC_END,
        "outImageSha256": sha(img),
        "outSyxSha256": sha(out_syx),
        "outCrc": f"{bp.zlib.crc32(img + b'\xFF' * (bp.CRC_REGION - len(img))) & 0xFFFFFFFF:08X}",
        "history": hist["releases"],
    }
    js = ("// Generated by tools/patch/gen_site.py. Do not edit by hand.\n"
          "// Our code and branch instructions only. No vendor bytes.\n"
          f"export const PATCH = {json.dumps(data, indent=2)};\n")
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    open(OUT_JS, "w", newline="\n").write(js)
    print(f"wrote {OUT_JS}: version {rel['version']} ({rel['build']}), "
          f"cave {len(cave)} bytes, {len(edits)} edits, output CRC {data['outCrc']}")


if __name__ == "__main__":
    main()
